// GeneratedHeader is the first line of every file the tool generates. It follows
// the Go convention (https://go.dev/s/generatedcode) so that linters, editors and
// code review tools treat the file as generated.
const GeneratedHeader = "// Code generated by struct-avro. DO NOT EDIT."

// ErrInvalidOutput is returned when an output directory, package or module
// name cannot be used for generated code.
var ErrInvalidOutput = errors.New("invalid code generation output")

// CheckDir creates dir and its parents if needed.
func CheckDir(dir string) error {
	return os.MkdirAll(dir, 0o750)
}

// PackageName checks that name can be a Go package name: an identifier that is
// not a keyword, and does not start with '_' (go:embed and the go tool skip
// directories starting with '_' or '.').
func PackageName(name string) error {
	if !token.IsIdentifier(name) || token.IsKeyword(name) || strings.HasPrefix(name, "_") {
		return fmt.Errorf("%w: %q is not a valid Go package name", ErrInvalidOutput, name)
	}
	return nil
}

// SetupModule runs "go mod init" and "go mod tidy" in dir.
func SetupModule(ctx context.Context, module string, dir string) error {
	for _, args := range [][]string{{"mod", "init", module}, {"mod", "tidy"}} {
		cmd := exec.CommandContext(ctx, "go", args...) // #nosec G204 -- fixed "go" binary; the module path is passed as one argument, never through a shell
		cmd.Dir = dir
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("go %s in %s: %w: %s", strings.Join(args, " "), dir, err, strings.TrimSpace(stderr.String()))
		}
	}
	return nil
}

// RenderCode executes tmpl and formats the result as Go source.
func RenderCode(tmpl *template.Template, data any) ([]byte, error) {
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}
	return FormatSource(buf.Bytes())
}

// FormatSource formats generated Go source like goimports: gofmt, then imports
// sorted and grouped (standard library first). It never adds or removes an
// import, so the output does not depend on the environment.
func FormatSource(src []byte) ([]byte, error) {
	return imports.Process("generated.go", src, &imports.Options{
		Comments:   true,
		TabIndent:  true,
		TabWidth:   8,
		FormatOnly: true,
	})
}

// WriteToFile writes b to path atomically: it writes a temporary file in the
// same directory and renames it, so a reader never sees a partial file and a
// failed write leaves the previous file in place.
func WriteToFile(path string, b []byte) (err error) {
	path = filepath.Clean(path)
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".tmp*")
	if err != nil {
		return err
	}
	defer func() {
		if err != nil {
			_ = os.Remove(tmp.Name())
		}
	}()
	if _, err = tmp.Write(b); err != nil {
		_ = tmp.Close()
		return err
	}
	if err = tmp.Close(); err != nil {
		return err
	}
	// Generated sources are committed and read by the go tool: 0644 like any
	// other source file.
	if err = os.Chmod(tmp.Name(), 0o644); err != nil { // #nosec G302 -- generated source code, not a secret
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// RemoveGenerated removes path if it exists and its first line is a generated
// header from struct-avro or its predecessor. Any other file is left alone and
// reported as an error, so the tool never deletes a file a person wrote.
func RemoveGenerated(path string) error {
	b, err := os.ReadFile(filepath.Clean(path))
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	head := string(b)
	if i := strings.IndexByte(head, '\n'); i >= 0 {
		head = head[:i]
	}
	if !strings.HasPrefix(head, "// Code generated by ") && !strings.HasPrefix(head, "/*") {
		return fmt.Errorf("%w: %s exists and was not generated", ErrInvalidOutput, path)
	}
	if strings.HasPrefix(head, "/*") && !bytes.Contains(b, []byte("Code Generated by ln80/")) {
		return fmt.Errorf("%w: %s exists and was not generated", ErrInvalidOutput, path)
	}
	return os.Remove(filepath.Clean(path))
}
