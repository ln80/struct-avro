func TestCustomTemplateImportsAreGrouped(t *testing.T) {
	out := filepath.Join(t.TempDir(), "events")
	writeStoreSchema(t, out, "bank", "1@aaaaaaaaaaaaaaaa.json", bankV1Schema(t).String())
	tmpl := `// Code generated by struct-avro. DO NOT EDIT.

package {{ .PackageName }}

import (
	"example.com/third/party"
	"time"
	"embed"
)

var _ = party.X
var _ time.Duration
var _ embed.FS
`
	err := tool.NewJobExecuter(nil).EmbedSchemas(fs.NewDirAdapter(out), tool.EmbedConfig{Out: out, Template: tmpl}).Execute(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(filepath.Join(out, "bank", "events.go"))
	if err != nil {
		t.Fatal(err)
	}
	want := "import (\n\t\"embed\"\n\t\"time\"\n\n\t\"example.com/third/party\"\n)"
	if !strings.Contains(string(b), want) {
		t.Fatalf("imports not grouped:\n%s", b)
	}
}
