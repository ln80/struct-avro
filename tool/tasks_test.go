// envelope mirrors event-store's avroEvent exported fields, tags and order.
type envelope struct {
	FStreamID         string        `avro:"StmID"`
	FRawGlobalVersion string        `avro:"GVer"`
	FRawVersion       string        `avro:"Ver"`
	FID               string        `avro:"ID"`
	FType             string        `avro:"Type"`
	FAt               int64         `avro:"At"`
	FUser             string        `avro:"User"`
	FIPAddr           string        `avro:"IPAddr"`
	FDests            []string      `avro:"Dests"`
	FTTL              time.Duration `avro:"TTL"`
	FRawEvent         any           `avro:"Data" ev:",inject=union"`
}

func bankV1Schema(t *testing.T) *avro.RecordSchema {
	t.Helper()
	sch, err := structavro.BuildEnvelopeSchema(structavro.NewAPI(), structavro.EnvelopeConfig{
		Namespace: "bank",
		RootType:  reflect.TypeOf(envelope{}),
		RootName:  "events",
		InjectKey: "union",
		Entries: []structavro.RecordEntry{
			{Name: "bank.AccountOpened", Type: reflect.TypeOf(bankv1.AccountOpened{}), Sample: bankv1.AccountOpened{}},
			{Name: "bank.MoneyDeposited", Type: reflect.TypeOf(bankv1.MoneyDeposited{}), Sample: bankv1.MoneyDeposited{}},
			{Name: "bank.MoneyWithdrawn", Type: reflect.TypeOf(bankv1.MoneyWithdrawn{}), Sample: bankv1.MoneyWithdrawn{}},
		},
		Validate: true,
	})
	if err != nil {
		t.Fatalf("build envelope: %v", err)
	}
	return sch
}

// silentPrinter satisfies internal.TaskPrinter without emitting output.
type silentPrinter struct{}

func (silentPrinter) Message(string, *internal.Task) {}
func (silentPrinter) Error(error, *internal.Task)    {}
func (silentPrinter) Task(int, internal.Task)        {}

func TestJobExecuterEndToEnd(t *testing.T) {
	ctx := context.Background()
	root := t.TempDir()
	store := filepath.Join(root, "registry")
	if err := os.MkdirAll(store, 0o750); err != nil {
		t.Fatal(err)
	}
	adapter := fs.NewDirAdapter(store)

	out := filepath.Join(root, "schemas")

	sch := bankV1Schema(t)

	job := tool.NewJobExecuter(silentPrinter{})
	job.
		GenerateSchemas(func(context.Context) (tool.SchemaMap, error) {
			return tool.SchemaMap{"bank": sch}, nil
		}).
		CheckCompatibility(adapter).
		PersistSchemas(adapter, adapter).
		EmbedSchemas(adapter, tool.EmbedConfig{Out: out})

	if err := job.Execute(ctx); err != nil {
		t.Fatalf("execute job: %v", err)
	}

	// The schema must have been persisted under the registry store.
	id, err := adapter.GetByDefinition(ctx, sch)
	if err != nil {
		t.Fatalf("schema not persisted: %v", err)
	}
	if id == "" {
		t.Fatal("empty schema id after persist")
	}

	// Embed must have generated Go event types + an embed.FS accessor.
	eventsGo := filepath.Join(out, "bank", "events.go")
	b, err := os.ReadFile(eventsGo)
	if err != nil {
		t.Fatalf("read generated events.go: %v", err)
	}
	src := string(b)
	for _, want := range []string{"package bank", "type AccountOpened struct", "type MoneyDeposited struct"} {
		if !strings.Contains(src, want) {
			t.Fatalf("generated events.go missing %q:\n%s", want, src)
		}
	}
	// The default (generic) template must NOT pull in event-store.
	if strings.Contains(src, "event-store") {
		t.Fatalf("generated code unexpectedly references event-store:\n%s", src)
	}

	assertGeneratedLayout(t, out, "bank", id)
	compileGenerated(t, root, out)
}

// assertGeneratedLayout checks the files EmbedSchemas writes under out.
func assertGeneratedLayout(t *testing.T, out, namespace, id string) {
	t.Helper()
	for _, name := range []string{
		filepath.Join(out, "embed.go"),
		filepath.Join(out, namespace, "events.go"),
	} {
		b, err := os.ReadFile(name)
		if err != nil {
			t.Fatal(err)
		}
		// https://go.dev/s/generatedcode: the header must come before the
		// package clause and end with a period.
		first, _, _ := strings.Cut(string(b), "\n")
		if first != "// Code generated by struct-avro. DO NOT EDIT." {
			t.Fatalf("%s: first line is %q", name, first)
		}
	}
	if _, err := os.Stat(filepath.Join(out, namespace, "1@"+id+".json")); err != nil {
		t.Fatalf("schema version not copied to the output: %v", err)
	}
	if _, err := os.Stat(filepath.Join(out, "init.go")); !os.IsNotExist(err) {
		t.Fatalf("init.go must not be generated, got %v", err)
	}
}

// compileGenerated type-checks the generated packages, go:embed patterns
// included, with the local toolchain and no network.
func compileGenerated(t *testing.T, root, out string) {
	t.Helper()
	gobin, err := exec.LookPath("go")
	if err != nil {
		t.Skip("go tool not found")
	}
	if err := os.WriteFile(filepath.Join(root, "go.mod"), []byte("module example.com/gen\n\ngo 1.25\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	rel, err := filepath.Rel(root, out)
	if err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(gobin, "vet", "./"+filepath.ToSlash(rel)+"/...")
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod", "GOPROXY=off", "GOTOOLCHAIN=local")
	if b, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("generated code does not compile: %v\n%s", err, b)
	}
}

// writeStoreSchema writes a raw schema version into a file store.
func writeStoreSchema(t *testing.T, store, namespace, name, body string) {
	t.Helper()
	dir := filepath.Join(store, namespace)
	if err := os.MkdirAll(dir, 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
}

func TestEmbedSchemasIntoTheStoreIsIdempotent(t *testing.T) {
	ctx := context.Background()
	root := t.TempDir()
	out := filepath.Join(root, "events")
	if err := os.MkdirAll(out, 0o750); err != nil {
		t.Fatal(err)
	}
	adapter := fs.NewDirAdapter(out)
	sch := bankV1Schema(t)

	run := func() map[string][]byte {
		t.Helper()
		err := tool.NewJobExecuter(nil).
			GenerateSchemas(func(context.Context) (tool.SchemaMap, error) { return tool.SchemaMap{"bank": sch}, nil }).
			CheckCompatibility(adapter).
			PersistSchemas(adapter, adapter).
			EmbedSchemas(adapter, tool.EmbedConfig{Out: out}).
			Execute(ctx)
		if err != nil {
			t.Fatal(err)
		}
		files := map[string][]byte{}
		_ = filepath.WalkDir(out, func(p string, d os.DirEntry, err error) error {
			if err == nil && !d.IsDir() {
				files[p], _ = os.ReadFile(p)
			}
			return err
		})
		return files
	}
	first, second := run(), run()
	if len(first) != 3 {
		t.Fatalf("expect 3 files (schema, events.go, embed.go), got %d", len(first))
	}
	for p, b := range first {
		if !bytes.Equal(b, second[p]) {
			t.Fatalf("%s changed on a second run", p)
		}
	}
	compileGenerated(t, root, out)
}

func TestEmbedSchemasReplacesLegacyInitFile(t *testing.T) {
	ctx := context.Background()
	out := filepath.Join(t.TempDir(), "events")
	adapter := fs.NewDirAdapter(out)
	writeStoreSchema(t, out, "bank", "1@aaaaaaaaaaaaaaaa.json", bankV1Schema(t).String())

	legacy := "/*\n * Code Generated by ln80/event-store. DO NOT EDIT.\n */\npackage events\n"
	if err := os.WriteFile(filepath.Join(out, "init.go"), []byte(legacy), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := tool.NewJobExecuter(nil).EmbedSchemas(adapter, tool.EmbedConfig{Out: out}).Execute(ctx); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(out, "init.go")); !os.IsNotExist(err) {
		t.Fatalf("legacy init.go must be removed, got %v", err)
	}

	// A file a person wrote is never removed.
	if err := os.WriteFile(filepath.Join(out, "init.go"), []byte("package events\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := tool.NewJobExecuter(nil).EmbedSchemas(adapter, tool.EmbedConfig{Out: out}).Execute(ctx); err == nil {
		t.Fatal("expect an error for a hand-written init.go")
	}
	if _, err := os.Stat(filepath.Join(out, "init.go")); err != nil {
		t.Fatalf("hand-written init.go must be kept: %v", err)
	}
}

func TestEmbedSchemasRejectsUnsafeSchemas(t *testing.T) {
	envelope := func(namespace, fields string) string {
		return `{"type":"record","name":"events","namespace":"` + namespace + `","fields":[` +
			`{"name":"Data","type":["null",{"type":"record","name":"Ev","fields":[` + fields + `]}]}]}`
	}
	cases := map[string]string{
		"doc with line break": envelope("bank", `{"name":"A","type":"string","doc":"x\n}\nfunc init() { panic(1) }\n//"}`),
		"tag with backquote":  envelope("bank", "{\"name\":\"A\",\"type\":\"string\",\"sensitive\":{\"ID\":\"pii\",\"Name\":\"data\",\"Options\":{\"kind\":\"a`b\"}}}"),
		"tag with quote":      envelope("bank", `{"name":"A","type":"string","sensitive":{"ID":"pii","Name":"da\"ta"}}`),
		"dotted namespace":    envelope("bank.v1", `{"name":"A","type":"string"}`),
		"keyword namespace":   envelope("func", `{"name":"A","type":"string"}`),
	}
	for name, body := range cases {
		t.Run(name, func(t *testing.T) {
			out := filepath.Join(t.TempDir(), "events")
			ns := "bank"
			if strings.Contains(body, `"namespace":"bank.v1"`) {
				ns = "bank.v1"
			} else if strings.Contains(body, `"namespace":"func"`) {
				ns = "func"
			}
			writeStoreSchema(t, out, ns, "1@aaaaaaaaaaaaaaaa.json", body)
			err := tool.NewJobExecuter(nil).EmbedSchemas(fs.NewDirAdapter(out), tool.EmbedConfig{Out: out}).Execute(context.Background())
			if err == nil {
				t.Fatal("expect error")
			}
			if _, err := os.Stat(filepath.Join(out, ns, "events.go")); !os.IsNotExist(err) {
				t.Fatalf("events.go must not be written, got %v", err)
			}
		})
	}
}

